// Lists everything in /media and writes media-manifest.js so the page knows which
// shots have a still or a clip. Vercel runs this on every deploy (see vercel.json).
// Run it yourself with `node build-manifest.js` after adding files if you preview locally.
const fs = require("fs");
const path = require("path");

const dir = path.join(__dirname, "media");
const ok = /\.(mp4|webm|mov|m4v|jpg|jpeg|png|webp|gif)$/i;
const prefer = ["mp4", "webm", "mov", "m4v", "jpg", "jpeg", "png", "webp", "gif"];
const manifest = {};

if (fs.existsSync(dir)) {
  for (const file of fs.readdirSync(dir).sort()) {
    if (!ok.test(file)) continue;
    const ext = path.extname(file).slice(1).toLowerCase();
    const key = path.basename(file, path.extname(file)).toLowerCase();
    const current = manifest[key];
    if (!current || prefer.indexOf(ext) < prefer.indexOf(path.extname(current).slice(1).toLowerCase())) {
      manifest[key] = `media/${encodeURIComponent(file)}`;
    }
  }
}

fs.writeFileSync(
  path.join(__dirname, "media-manifest.js"),
  `// Generated by build-manifest.js. Do not edit by hand.\nwindow.MEDIA_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`
);
console.log(`media-manifest.js: ${Object.keys(manifest).length} file(s)`);
